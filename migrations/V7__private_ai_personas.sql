-- One active configuration per room and AI member. Removing that membership
-- removes this configuration, but NOT generation control records or history.
CREATE TABLE room_ai_personas (
    room_id         BIGINT UNSIGNED NOT NULL,
    member_id       BIGINT UNSIGNED NOT NULL,
    admission_id    BINARY(16) NOT NULL,
    persona         TEXT NOT NULL,
    persona_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    PRIMARY KEY (room_id, member_id),
    UNIQUE KEY uq_room_ai_admission (admission_id),
    CONSTRAINT fk_room_ai_membership FOREIGN KEY (room_id, member_id)
        REFERENCES room_members (room_id, member_id) ON DELETE CASCADE,
    CONSTRAINT fk_room_ai_profile FOREIGN KEY (member_id)
        REFERENCES ai_profiles (member_id),
    CONSTRAINT ck_room_ai_admission CHECK (admission_id <> UNHEX(REPEAT('00', 16))),
    CONSTRAINT ck_room_ai_persona_version CHECK (persona_version > 0),
    CONSTRAINT ck_room_ai_persona_size CHECK (OCTET_LENGTH(persona) <= 16384)
);

-- Existing AIs keep their TOML default persona; this empty value is not a
-- replacement for that deployed configuration. UUIDs only backfill old rows;
-- future admissions use random 16-byte tokens generated by the application.
INSERT INTO room_ai_personas (room_id, member_id, admission_id, persona)
SELECT rm.room_id, rm.member_id, UNHEX(REPLACE(UUID(), '-', '')), ''
FROM room_members rm JOIN ai_profiles p ON p.member_id = rm.member_id;

-- Old pending requests remain intact. New private-role requests will supply
-- an explicit persona, including the empty string when that is intended.
ALTER TABLE ai_member_requests
    ADD COLUMN persona TEXT NULL,
    ADD CONSTRAINT ck_ai_request_persona_size CHECK (
        persona IS NULL OR OCTET_LENGTH(persona) <= 16384
    );

-- Nullable as a group so V6 writers and in-flight legacy generations still
-- work. The future private-role protocol must supply all three fields.
-- Deliberately no FK to room_ai_personas: removing/rejoining a member must
-- not erase old generation fences or make an old response valid again.
ALTER TABLE ai_generations
    ADD COLUMN admission_id BINARY(16) NULL,
    ADD COLUMN persona_version BIGINT UNSIGNED NULL,
    ADD COLUMN persona_snapshot TEXT NULL,
    ADD KEY idx_generations_admission (room_id, member_id, admission_id, status),
    ADD CONSTRAINT ck_ai_generation_persona CHECK (
        (admission_id IS NULL AND persona_version IS NULL AND persona_snapshot IS NULL)
        OR (admission_id IS NOT NULL AND admission_id <> UNHEX(REPEAT('00', 16))
            AND persona_version IS NOT NULL AND persona_version > 0
            AND persona_snapshot IS NOT NULL AND OCTET_LENGTH(persona_snapshot) <= 16384)
    );
