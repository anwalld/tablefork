-- Model types are configuration keys, not individual room members. Actual
-- provider model names continue to live in ai/agents.toml.
CREATE TABLE ai_model_types (
    model_slug   VARCHAR(32) NOT NULL PRIMARY KEY,
    display_name VARCHAR(64) NOT NULL,
    provider     ENUM('deepseek', 'openai', 'anthropic', 'gemini') NOT NULL,
    UNIQUE KEY uq_ai_model_provider (model_slug, provider)
);

